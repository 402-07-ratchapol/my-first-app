st.title("🚗 แอปพลิเคชั่นคำนวณความโค้งที่อันตราย")

# 1. แก้ไขพิมพ์ผิดระยt -> ระยะ และกำหนด step ให้กรอกง่ายขึ้น
m = st.number_input("ระยะคอร์ด / การกระจัดของโค้ง (เมตร):", value=0.0, step=1.0)
c = st.number_input("ระยะจากกึ่งกลางคอร์ดจนถึงส่วนโค้ง (เมตร):", value=0.0, step=1.0)

# ตรวจสอบป้องกันการหารด้วยศูนย์ (Division by Zero)
if m > 0:
    # 2. แก้ไขสูตรคำนวณรัศมีโค้ง (R) ใส่สัญลักษณ์วงเล็บให้ลำดับการคูณหารถูกต้อง
    # สูตรจริง: R = (c^2 / (8 * m)) + (m / 2)
    R = (c ** 2 / (8 * m)) + (m / 2)
    
    # 3. แก้ไขชื่อตัวแปรจาก V(max) เป็น v_max (Python ห้ามตั้งชื่อตัวแปรมีวงเล็บ)
    # สูตรความเร็วปลอดภัยสูงสุด: v = sqrt(R * 127 * f) โดย f = 0.2 คือแรงเสียดทานทางข้าง
    v_max = (R * 127 * 0.2) ** 0.5
    
    # 4. แก้ไขข้อความสรุปผลลัพธ์ เปลี่ยนจาก "บาท/VAT" เป็นหน่วยวัดระยะทางและความเร็วที่ถูกต้อง
    st.header(f"• รัศมีโค้ง (R): **{R:.2f}** เมตร")
    st.header(f"• ความเร็วปลอดภัยสูงสุด (V max): **{v_max:.2f}** กิโลเมตร/ชั่วโมง")

else:
    st.warning("⚠️ กรุณากรอกระยะการกระจัดของโค้ง (m) ให้มากกว่า 0 เพื่อเริ่มคำนวณ")

st.divider()
