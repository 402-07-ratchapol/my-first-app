import streamlit as st

st.title("🚗 แอปพลิเคชั่นคำนวณความโค้งที่อันตราย")

# 1. รับค่าอินพุตจากผู้ใช้งาน
m = st.number_input("ระยะคอร์ด / การกระจัดของโค้ง (เมตร):", value=0.0, step=1.0)
c = st.number_input("ระยะจากกึ่งกลางคอร์ดจนถึงส่วนโค้ง (เมตร):", value=0.0, step=1.0)

# ตรวจสอบป้องกันการหารด้วยศูนย์ (Division by Zero)
if m > 0:
    # 2. สูตรคำนวณรัศมีโค้ง (R)
    R = (c ** 2 / (8 * m)) + (m / 2)
    
    # 3. สูตรความเร็วปลอดภัยสูงสุด (v_max)
    v_max = (R * 127 * 0.2) ** 0.5
    
    # 4. แสดงข้อความสรุปผลลัพธ์โครงสร้างกายภาพ
    st.header(f"• รัศมีโค้ง (R): **{R:.2f}** เมตร")
    st.header(f"• ความเร็วปลอดภัยสูงสุด (V max): **{v_max:.2f}** กิโลเมตร/ชั่วโมง")
    
    st.write("---")
    st.subheader("🧐 ผลการประเมินระดับความอันตรายของโค้ง")

    # 5. [แก้ไข] ย้ายการตรวจสอบทั้งหมดเข้ามาอยู่ภายใต้ `if m > 0:` และจัดระเบียบย่อหน้าให้เสมอกัน
    # ประเภทที่ 1: โค้งศอกกลับ หรือโค้งหักศอก (R น้อยกว่า 20 เมตร)
    if R < 20:
        st.info("📌 **ประเภทโค้ง:** โค้งศอกกลับ หรือโค้งหักศอก")
        if v_max <= 20: # ปรับให้ครอบคลุมค่าน้อยกว่าหรือเท่ากับ 20
            st.success("✔️ โค้งที่ปลอดภัย")
        elif 20 < v_max <= 30:
            st.warning("❗ โค้งเริ่มอันตราย")
        elif v_max > 30:
            st.error("🛑 โค้งนี้อันตรายมาก")
            
    # ประเภทที่ 2: โค้งฉาก หรือโค้งหักมุม (R ระหว่าง 20 ถึง 80 เมตร)
    elif 20 <= R < 80:
        st.info("📌 **ประเภทโค้ง:** โค้งฉาก หรือโค้งหักมุม")
        if v_max <= 30:
            st.success("✔️ โค้งที่ปลอดภัย")
        elif 30 < v_max <= 40:
            st.warning("❗ โค้งเริ่มอันตราย")
        elif v_max > 40:
            st.error("🛑 โค้งนี้อันตรายมาก")
            
    # ประเภทที่ 3: โค้งวงกว้างยาวต่อเนื่อง (R มากกว่าหรือเท่ากับ 80 เมตร)
    elif 80 <= R:
        st.info("📌 **ประเภทโค้ง:** โค้งวงกว้างยาวต่อเนื่อง")
        if v_max <= 40:
            st.success("✔️ โค้งที่ปลอดภัย")
        elif 40 < v_max <= 50:
            st.warning("❗ โค้งเริ่มอันตราย")
        elif v_max > 50:
            st.error("🛑 โค้งนี้อันตรายมาก")

else:
    st.warning("⚠️ กรุณากรอกระยะการกระจัดของโค้ง (m) ให้มากกว่า 0 เพื่อเริ่มคำนวณ")

st.divider()
